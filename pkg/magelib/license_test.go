// TestNoticeCarriesAllThreeParts. Operator decision 17 takes the
// copyright line, Exhibit A verbatim AND the SPDX identifier, because
// they answer to different readers: section 1.4 names Exhibit A as what
// makes a file Covered Software, while scanners read the identifier.
// Dropping either half silently would satisfy neither reader fully.
func TestNoticeCarriesAllThreeParts(t *testing.T) {
	n, err := testLicense().Notice(".go")
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	for _, want := range []string{
		"// Copyright (c) 2026 Steven Verhelle (enqack)",
		"// This Source Code Form is subject to the terms of the Mozilla Public",
		"// License, v. 2.0. If a copy of the MPL was not distributed with this",
		"// file, You can obtain one at https://mozilla.org/MPL/2.0/.",
		"// " + mplSPDX,
	} {
		if !strings.Contains(n, want) {
			t.Fatalf("notice is missing %q:\n%s", want, n)
		}
	}
	// A trailing space inside a comment survives gofmt, so it would
	// make the notice differ from itself by whitespace nobody can see
	// and an exact-match check would fail on files it had written.
	for _, line := range strings.Split(strings.TrimSuffix(n, "\n"), "\n") {
		if line != strings.TrimRight(line, " \t") {
			t.Fatalf("line has trailing whitespace: %q", line)
		}
	}
}

// TestNoticeUsesHashForScriptLanguages. Rendering a Go comment into a
// shell script produces a file whose first line is a syntax error, and
// the sweep would apply it everywhere before anyone ran a script.
func TestNoticeUsesHashForScriptLanguages(t *testing.T) {
	for _, ext := range []string{".py", ".sh", ".nix"} {
		n, err := testLicense().Notice(ext)
		if err != nil {
			t.Fatalf("%s: %v", ext, err)
		}
		// Asserted per LINE, not as a substring: Exhibit A carries the
		// MPL URL, whose "//" would match a whole-string search and
		// make this assertion fail against a correct notice.
		for _, line := range strings.Split(strings.TrimSuffix(n, "\n"), "\n") {
			if strings.HasPrefix(line, "//") {
				t.Fatalf("%s rendered a Go comment line %q:\n%s", ext, line, n)
			}
		}
		if !strings.HasPrefix(n, "# Copyright") {
			t.Fatalf("%s did not render a hash comment:\n%s", ext, n)
		}
	}
}
